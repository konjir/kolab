/**
 * The verbs' parameters as their schemas give them (W5.7): `konjir tools`, `konjir help <verb>` and
 * docs/verbs.md are all made here, from the input schemas Kolab serves, never written by hand.
 */

interface JsonSchema {
  type?: string | string[]; enum?: unknown[]; const?: unknown; description?: string;
  items?: JsonSchema; anyOf?: JsonSchema[]; oneOf?: JsonSchema[];
  properties?: Record<string, JsonSchema>; required?: string[]; additionalProperties?: unknown;
}

/** A tool as MCP lists it: what these functions read of it. */
export interface ListedTool { name: string; description?: string; inputSchema: unknown }

/** A parameter's type in a word or two: an enum's values, a list's items, an object's keys. */
export function typeOf(p: JsonSchema | undefined): string {
  if (!p) return 'json';
  if (p.enum) return p.enum.map(String).join('|');
  if (p.const !== undefined) return JSON.stringify(p.const);
  const alts = p.anyOf ?? p.oneOf;
  if (alts) return [...new Set(alts.map((a) => typeOf(a)))].join('|');
  const t = Array.isArray(p.type) ? p.type.join('|') : p.type;
  if (t === 'array') return `[${typeOf(p.items)}]`;
  if (t === 'object') {
    const keys = Object.keys(p.properties ?? {});
    return keys.length ? `{${keys.map((k) => `${k}${p.required?.includes(k) ? '' : '?'}`).join(',')}}` : 'object';
  }
  if (t === 'integer') return 'int';
  return t ?? 'json';
}

/** A verb's parameters: each one's name, type, whether it is required, and its description. */
export function paramsOf(tool: ListedTool): { name: string; type: string; required: boolean; description?: string }[] {
  const s = (tool.inputSchema ?? {}) as JsonSchema;
  return Object.entries(s.properties ?? {}).map(([name, p]) => ({ name, type: typeOf(p), required: !!s.required?.includes(name), description: p.description }));
}

/** The verb's name as the CLI takes it: konjir_ dropped. */
export const verbName = (tool: ListedTool) => tool.name.replace(/^konjir_/, '');

/** One line of a verb's usage: `create_node kind=<spec|…> title=<string> [id=<string>]`, required first. */
export function usageLine(tool: ListedTool): string {
  const ps = paramsOf(tool).sort((a, b) => Number(b.required) - Number(a.required));
  return [verbName(tool), ...ps.map((p) => (p.required ? `${p.name}=<${p.type}>` : `[${p.name}=<${p.type}>]`))].join(' ');
}

/** The first sentence of a description, for a one-line listing. */
export function firstSentence(text = ''): string {
  const m = /^(.+?[.!?])(\s|$)/s.exec(text.trim());
  return (m ? m[1] : text.trim()).replace(/\s+/g, ' ');
}

/** `konjir tools`: each verb's usage, then the first sentence of what it does. */
export function toolsListing(tools: ListedTool[]): string {
  return [...tools].sort((a, b) => a.name.localeCompare(b.name))
    .map((t) => `${usageLine(t)}\n    ${firstSentence(t.description)}`).join('\n');
}

/** `konjir help <verb>`: its usage, its description, and each parameter. */
export function verbHelp(tool: ListedTool): string {
  const params = paramsOf(tool).map((p) => `  ${p.name}${p.required ? '' : ' (optional)'}: ${p.type}${p.description ? ` — ${p.description}` : ''}`);
  return [`konjir ${usageLine(tool)}`, '', tool.description ?? '', '', params.length ? params.join('\n') : '  (no parameters)'].join('\n');
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

/** docs/verbs.md: every verb, its usage and a table of its parameters, from the schemas Kolab serves. */
export function verbsMarkdown(tools: ListedTool[]): string {
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name));
  const out = [
    '# Kolab verbs',
    '',
    '<!-- Generated by `npm run verbs` (apps/cli/src/verbs.ts) from the schemas Kolab serves. Do not edit by hand: apps/cli/test/verbs.test.ts fails when it is out of date. -->',
    '',
    'Every verb, as `konjir <verb> key=value …` takes it from a shell and as the MCP tool `konjir_<verb>`. Values parse as JSON when they can (`elements=\'[{"id":"R1","text":"…"}]\'`); `--json \'{…}\'` gives every argument as one object. A verb refuses an argument it doesn\'t take, naming it and the ones it takes. `konjir help <verb>` prints the same for one verb, and `konjir tools` lists them all. The `admin_` verbs are for a Konjir admin\'s own session or the break-glass token.',
    '',
    '| Verb | Does |',
    '| --- | --- |',
    ...sorted.map((t) => `| [\`${verbName(t)}\`](#${verbName(t)}) | ${cell(firstSentence(t.description))} |`),
    '',
  ];
  for (const t of sorted) {
    const ps = paramsOf(t);
    out.push(`## ${verbName(t)}`, '', '```', `konjir ${usageLine(t)}`, '```', '', cell(t.description ?? ''), '');
    if (ps.length) {
      out.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |');
      for (const p of ps) out.push(`| \`${p.name}\` | \`${cell(p.type)}\` | ${p.required ? 'yes' : 'no'} | ${cell(p.description ?? '')} |`);
    } else out.push('No parameters.');
    out.push('');
  }
  return out.join('\n');
}

/**
 * Every verb a Kolab serves, admin verbs included, from a throwaway in-memory Kolab: what
 * docs/verbs.md is made from (`npm run verbs`). Development only: it starts the server.
 */
export async function servedTools(): Promise<ListedTool[]> {
  const { startServer } = await import('@konjir/server');
  const { connect } = await import('./cli.js');
  const admin = 'verbs-doc-admin-token';
  const server = await startServer({ adminToken: admin, webRoot: null });
  try {
    const client = await connect(server.url, admin);
    try {
      return (await client.listTools()).tools;
    } finally {
      await client.close();
    }
  } finally {
    await server.close();
  }
}
